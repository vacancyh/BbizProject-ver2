import "server-only"
import { cookies as nextCookies } from "next/headers"

export const getAuthHeaders = async (): Promise<
  { authorization: string } | Record<string, never>
> => {
  try {
    const cookies = await nextCookies()
    const token = cookies.get("_medusa_jwt")?.value

    if (!token) {
      return {}
    }

    return { authorization: `Bearer ${token}` }
  } catch {
    return {}
  }
}

export const getCacheTag = async (tag: string): Promise<string> => {
  try {
    const cookies = await nextCookies()
    const cacheId = cookies.get("_medusa_cache_id")?.value

    if (!cacheId) {
      return ""
    }

    return `${tag}-${cacheId}`
  } catch {
    return ""
  }
}

export const getCacheOptions = async (
  tag: string
): Promise<{ tags: string[] } | Record<string, never>> => {
  if (typeof window !== "undefined") {
    return {}
  }

  // 방문자별 태그(`${tag}-${cacheId}`) — 방문자 캐시 분리용(기존 동작 유지).
  const cacheTag = await getCacheTag(tag)

  // 안정 태그(base 그대로) — on-demand revalidateTag(base) 가 매칭할 수 있도록
  // 항상 함께 부착한다. cacheId 쿠키 유무와 무관하게 백엔드 webhook 이
  // 무효화할 수 있는 전역 태그를 보장한다(§V0 재발방지: revalidate-tags.ts 계약).
  // 주의: cacheId 가 없으면 cacheTag 는 빈 문자열이므로 안정 태그만 남긴다.
  const tags = cacheTag ? [cacheTag, tag] : [tag]

  return { tags }
}

export const setAuthToken = async (token: string) => {
  const cookies = await nextCookies()
  cookies.set("_medusa_jwt", token, {
    maxAge: 60 * 60 * 24 * 7,
    httpOnly: true,
    sameSite: "strict",
    secure: process.env.NODE_ENV === "production",
  })
}

export const removeAuthToken = async () => {
  const cookies = await nextCookies()
  cookies.set("_medusa_jwt", "", {
    maxAge: -1,
  })
}

